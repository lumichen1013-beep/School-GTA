/**
 * 廣播台詞洗牌循環佇列：保證每輪不重複，且跨輪時最後一句不與新一輪第一句相同
 */
export class AnnouncementPlaylist {
  private playlist: number[] = [];
  private lastIndex: number = -1;

  public next(): string {
    if (this.playlist.length === 0) {
      const indices = Array.from({ length: ANNOUNCEMENTS.length }, (_, i) => i);
      for (let i = indices.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [indices[i], indices[j]] = [indices[j], indices[i]];
      }
      // 避免跨循環時最後一句與新循環第一句重複
      if (indices.length > 1 && indices[indices.length - 1] === this.lastIndex) {
        const swapIdx = Math.floor(Math.random() * (indices.length - 1));
        [indices[indices.length - 1], indices[swapIdx]] = [indices[swapIdx], indices[indices.length - 1]];
      }
      this.playlist = indices;
    }
    const nextIdx = this.playlist.pop()!;
    this.lastIndex = nextIdx;
    return ANNOUNCEMENTS[nextIdx];
  }
}
